#!/usr/bin/env python3
"""Compute symbol / gem / wild / feature statistics from spins.csv.

Usage:  python3 research/go-ghost/analyze.py
Writes: research/go-ghost/summary.md
"""
import csv
import os
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
CSV_PATH = os.path.join(HERE, "spins.csv")
OUT_PATH = os.path.join(HERE, "summary.md")

REELS = [f"R{r}" for r in range(1, 6)]
ROWS = ["T", "M", "B"]
CELLS = [f"{r}{p}" for r in REELS for p in ROWS]
SYMBOLS = ["J", "Q", "K", "A", "CUF", "CHN", "MIR", "BOOK", "MAN", "WILD", "GEM", "FG", "GHOST"]
SYMBOL_NAMES = {
    "J": "J", "Q": "Q", "K": "K", "A": "A",
    "CUF": "Cufflinks", "CHN": "Chandelier", "MIR": "Hand mirror", "BOOK": "Book",
    "MAN": "Mustache man", "WILD": "Wild", "GEM": "Gem (cash/jackpot)",
    "FG": "Free Games scatter", "GHOST": "Ghost",
}
JACKPOT_LABELS = {"MINI", "MINOR", "MAJOR", "MAXI"}


def load():
    with open(CSV_PATH, newline="") as f:
        return list(csv.DictReader(f))


def parse_gems(s):
    out = []
    if not s:
        return out
    for g in s.split(";"):
        pos, color, val = g.split(":")
        out.append((pos, color, val))
    return out


def pct(n, d):
    return f"{100 * n / d:.1f}%" if d else "n/a"


def table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    for r in rows:
        lines.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(lines)


def reel_symbol_section(spins, title):
    per_reel = {r: Counter() for r in REELS}
    for s in spins:
        for r in REELS:
            for p in ROWS:
                v = s[f"{r}{p}"]
                if v != "?":
                    per_reel[r][v] += 1
    totals = {r: sum(per_reel[r].values()) for r in REELS}
    overall = Counter()
    for r in REELS:
        overall.update(per_reel[r])
    grand = sum(overall.values())
    rows = []
    for sym in SYMBOLS:
        rows.append([SYMBOL_NAMES[sym]] + [pct(per_reel[r][sym], totals[r]) for r in REELS]
                    + [pct(overall[sym], grand), overall[sym]])
    rows.append(["**cells observed**"] + [totals[r] for r in REELS] + ["", grand])
    out = [f"### {title}", "",
           f"Share of visible cells on each reel showing each symbol ({len(spins)} spins).", "",
           table(["Symbol"] + REELS + ["All reels", "Count"], rows)]
    return "\n".join(out), per_reel, totals


def per_spin_count_dist(spins, sym):
    c = Counter()
    for s in spins:
        c[sum(1 for cell in CELLS if s[cell] == sym)] += 1
    return c


def stack_runs(spins, sym):
    """Distribution of vertical run lengths of `sym` within each reel window."""
    runs = Counter()
    for s in spins:
        for r in REELS:
            col = [s[f"{r}{p}"] for p in ROWS]
            if "?" in col:
                continue
            n = 0
            for v in col + [None]:
                if v == sym:
                    n += 1
                elif n:
                    runs[n] += 1
                    n = 0
    return runs


def main():
    data = load()
    screens = Counter(s["screen"] for s in data)
    reel_screens = [s for s in data if s["screen"] in ("base", "free")]
    base = [s for s in data if s["screen"] == "base"]
    free = [s for s in data if s["screen"] == "free"]
    base_full = [s for s in base if all(s[c] != "?" for c in CELLS)]

    md = []
    md.append("# Go Ghost — observed reel statistics")
    md.append("")
    md.append("Auto-generated by `analyze.py` from `spins.csv`. Re-run after adding rows.")
    md.append("")

    # ---- Data overview
    md.append("## Data overview")
    md.append("")
    md.append(table(["Screen type", "Screenshots"], sorted(screens.items(), key=lambda x: -x[1])))
    md.append("")
    by_sess = defaultdict(Counter)
    for s in base:
        by_sess[s["session"]][(s["denom"], s["bet"])] += 1
    rows = []
    for sess in sorted(by_sess):
        for (d, b), n in sorted(by_sess[sess].items(), key=lambda x: (float(x[0][0]), float(x[0][1]))):
            credits = round(float(b) / float(d))
            rows.append([sess, f"${float(d):.2f}", f"${float(b):.2f}", credits, n])
    md.append("Base-game spins by bet setting (credits bet = bet ÷ denomination):")
    md.append("")
    md.append(table(["Session", "Denom", "Bet", "Credits bet", "Base spins"], rows))
    md.append("")

    # ---- Symbol frequencies
    md.append("## Symbol frequency per reel")
    md.append("")
    md.append("These percentages estimate each reel strip's makeup: with a long enough sample, "
              "the share of visible cells showing a symbol converges on that symbol's share of the strip "
              "(weighted by stacking).")
    md.append("")
    sec, base_reel, base_tot = reel_symbol_section(base, "Base game")
    md.append(sec)
    md.append("")
    sec, _, _ = reel_symbol_section(free, "Free games")
    md.append(sec)
    md.append("")
    md.append("Free-games sample is small; treat as indicative only.")
    md.append("")

    # Approximate symbols-per-100-stop strip for building reels
    md.append("### Suggested strip weights (base game, per 100 stops)")
    md.append("")
    md.append("Base-game per-reel frequencies scaled to 100 stops and rounded. "
              "A starting point for a reel strip, not a measured strip.")
    md.append("")
    rows = []
    for sym in SYMBOLS:
        rows.append([SYMBOL_NAMES[sym]] + [round(100 * base_reel[r][sym] / base_tot[r]) for r in REELS])
    md.append(table(["Symbol"] + REELS, rows))
    md.append("")

    # ---- Stacking
    md.append("## Stacking (base game)")
    md.append("")
    md.append("Vertical run lengths within the 3-row window on fully visible reels. "
              "A run of 3 means the whole reel was covered.")
    md.append("")
    rows = []
    for sym in ["MAN", "WILD", "BOOK", "CUF", "CHN", "MIR", "J", "Q", "K", "A"]:
        runs = stack_runs(base, sym)
        tot = sum(runs.values())
        rows.append([SYMBOL_NAMES[sym], tot, runs[1], runs[2], runs[3], pct(runs[2] + runs[3], tot)])
    md.append(table(["Symbol", "Runs", "1-high", "2-high", "3-high", "2+ share"], rows))
    md.append("")

    # ---- Wilds
    md.append("## Wilds (base game)")
    md.append("")
    wd = per_spin_count_dist(base_full, "WILD")
    n = len(base_full)
    any_w = n - wd[0]
    md.append(f"- Spins with at least one wild: **{any_w}/{n} = {pct(any_w, n)}** (fully visible spins only)")
    md.append(f"- Wild positions by reel: " + ", ".join(
        f"{r} {base_reel[r]['WILD']}" for r in REELS))
    md.append("")
    md.append(table(["Wilds on screen", "Spins", "Share"],
                    [[k, wd[k], pct(wd[k], n)] for k in sorted(wd)]))
    md.append("")

    # ---- Gems
    md.append("## Gems")
    md.append("")
    gem_spins = [s for s in reel_screens]
    gem_all = []  # (spin, pos, color, val)
    for s in gem_spins:
        for g in parse_gems(s["gems"]):
            gem_all.append((s, *g))
    base_gems = [g for g in gem_all if g[0]["screen"] == "base"]
    gd = Counter(len(parse_gems(s["gems"])) for s in base)
    nb = len(base)
    md.append(f"Base game: **{len(base_gems)} gems over {nb} spins** "
              f"(avg {len(base_gems) / nb:.2f} per spin). "
              f"Spins with ≥1 gem: {pct(nb - gd[0], nb)}.")
    md.append("")
    md.append(table(["Gems on screen", "Spins", "Share"], [[k, gd[k], pct(gd[k], nb)] for k in sorted(gd)]))
    md.append("")
    by_reel = Counter(g[1][:2] for g in base_gems)
    by_row = Counter(g[1][2] for g in base_gems)
    md.append("Gem position:")
    md.append("")
    md.append(table(["", *REELS], [["Gems", *[by_reel[r] for r in REELS]]]))
    md.append("")
    md.append(table(["Row", "Top", "Middle", "Bottom"], [["Gems", by_row["T"], by_row["M"], by_row["B"]]]))
    md.append("")
    colors = Counter(g[2] for g in base_gems)
    md.append("Gem colour: " + ", ".join(f"{c} {colors[c]} ({pct(colors[c], len(base_gems))})"
                                          for c in sorted(colors, key=lambda c: -colors[c])))
    md.append("")

    # Gem values as multiple of credits bet
    md.append("### Gem values")
    md.append("")
    md.append("The number on a gem is in credits and scales with the credits bet, "
              "so values are shown as a multiple of the total bet (value ÷ credits bet). "
              "Jackpot gems (MINI/MINOR/MAJOR/MAXI) are counted separately.")
    md.append("")
    mult = Counter()
    jp = Counter()
    unknown = 0
    color_mult = defaultdict(Counter)
    for s, pos, color, val in base_gems:
        if val in JACKPOT_LABELS:
            jp[val] += 1
            continue
        if val == "?":
            unknown += 1
            continue
        credits = float(s["bet"]) / float(s["denom"])
        m = round(float(val) / credits, 2)
        mult[m] += 1
        color_mult[color][m] += 1
    cash_n = sum(mult.values())
    rows = []
    cum = 0
    for m in sorted(mult):
        cum += mult[m]
        rows.append([f"{m:g}x", mult[m], pct(mult[m], cash_n), pct(cum, cash_n)])
    md.append(table(["Value ÷ bet", "Gems", "Share", "Cumulative"], rows))
    md.append("")
    avg = sum(m * c for m, c in mult.items()) / cash_n if cash_n else 0
    md.append(f"- Cash gems: {cash_n}; mean value **{avg:.2f}× bet**; unreadable values: {unknown}")
    md.append(f"- Jackpot gems: " + (", ".join(f"{k} {jp[k]}" for k in ["MINI", "MINOR", "MAJOR", "MAXI"] if jp[k])
                                    or "none")
              + f" — {sum(jp.values())} of {len(base_gems)} gems ({pct(sum(jp.values()), len(base_gems))})")
    md.append("")
    rows = []
    for c in sorted(color_mult):
        cm = color_mult[c]
        t = sum(cm.values())
        rows.append([c, t, f"{sum(m * k for m, k in cm.items()) / t:.2f}x", f"{min(cm):g}x", f"{max(cm):g}x"])
    md.append(table(["Colour", "Cash gems", "Mean", "Min", "Max"], rows))
    md.append("")

    # ---- Free games scatter
    md.append("## Free Games scatter (base game)")
    md.append("")
    fd = per_spin_count_dist(base_full, "FG")
    md.append(table(["FG symbols on screen", "Spins", "Share"],
                    [[k, fd[k], pct(fd[k], len(base_full))] for k in sorted(fd)]))
    md.append("")
    md.append("FG landed on reels: " + ", ".join(f"{r} {base_reel[r]['FG']}" for r in REELS))
    md.append("")

    # ---- Ghost
    md.append("## Ghost symbol")
    md.append("")
    gh = [s for s in data if any(s[c] == "GHOST" for c in CELLS)]
    md.append(f"Ghost seen on {len(gh)} screenshots: " + ", ".join(
        f"#{s['idx']} ({s['screen']}, {[c for c in CELLS if s[c] == 'GHOST'][0]})" for s in gh))
    md.append("")
    md.append(f"Ghost-feature award screens: {screens.get('ghost_award', 0)}; "
              f"jackpot pick screens: {screens.get('jackpot_pick', 0)}; "
              f"free-games award screens: {screens.get('fg_award', 0)}.")
    md.append("")

    # ---- Events
    md.append("## Feature events log")
    md.append("")
    keys = ("TRIGGER", "FEATURE", "AWARDED", "JACKPOT PICK", "GHOST R", "MAXI", "MAJOR", "refill", "credit +", "GAP")
    rows = []
    for s in data:
        note = s["notes"]
        if any(k in note for k in keys) or s["screen"] in ("ghost_award", "jackpot_pick", "fg_award"):
            rows.append([s["idx"], s["time"], s["session"], s["screen"], f"${float(s['bet']):.2f}",
                         s["credit"], note.replace("|", "/")])
    md.append(table(["#", "Time", "Sess", "Screen", "Bet", "Credit", "Note"], rows))
    md.append("")

    # ---- Rough feature rates
    md.append("## Rough feature rates (low confidence)")
    md.append("")
    nb = len(base)
    fg_trig = sum(1 for s in data if "FREE GAMES TRIGGER" in s["notes"]
                  or s["screen"] == "free" and "5 left" in s["notes"] and "not captured" in s["notes"])
    ghost_trig = screens.get("ghost_award", 0)
    md.append(f"- Free games triggers seen: {fg_trig} in ~{nb} base spins (≈1 in {nb // max(fg_trig, 1)})")
    md.append(f"- Ghost feature awards seen: {ghost_trig} (≈1 in {nb // max(ghost_trig, 1)})")
    md.append(f"- Jackpot pick features seen: {screens.get('jackpot_pick', 0)}")
    md.append("")
    md.append("Some features happened off-camera (credit jumps with no feature screenshots), "
              "so these rates are lower bounds.")
    md.append("")

    with open(OUT_PATH, "w") as f:
        f.write("\n".join(md))
    print(f"wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
